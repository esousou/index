export const DICTS: Record<LangCode, Dict> = { en, zh, ko, ja, es, fr };

export function translate(lang: LangCode, key: Key, vars?: Record<string, string | number>) {
  let out: string = DICTS[lang][key] ?? DICTS.en[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.split(`{${k}}`).join(String(v));
    }
  }
  return out;
}

export function detectLang(): LangCode {
  if (typeof navigator === "undefined") return "en";
  const candidates = [navigator.language, ...(navigator.languages ?? [])];
  for (const c of candidates) {
    const n = c.toLowerCase();
    if (n.startsWith("zh")) return "zh";
    if (n.startsWith("ko")) return "ko";
    if (n.startsWith("ja")) return "ja";
    if (n.startsWith("es")) return "es";
    if (n.startsWith("fr")) return "fr";
    if (n.startsWith("en")) return "en";
  }
  return "en";
}
